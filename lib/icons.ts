export const ICON_NAMES = Object.keys(ICONS);

export const iconNameSchema = z.enum(ICON_NAMES).describe(
  "Choose the curated icon name that matches this item's meaning. Do not use star as a generic placeholder.",
);
const iconColorSchema = z.string().refine(
  (value) => value === "auto" || Object.hasOwn(THEME_COLOR_TOKENS, value) || /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(value),
  "Choose a theme color or a valid hex color.",
);
export const iconValueSchema = z.union([
  iconNameSchema,
  z.strictObject({
    name: iconNameSchema,
    size: z.number().int().min(12).max(96).optional(),
    color: iconColorSchema.optional(),
  }),
]);
export type IconValue = string | { name: string; size?: number; color?: string };

/** Legacy name strings retain their original size and inherited color. */
export function readIcon(value: unknown): { name: string; size?: number; color?: string } {
  const parsed = iconValueSchema.safeParse(value);
  if (!parsed.success) return { name: "star" };
  return typeof parsed.data === "string" ? { name: parsed.data } : parsed.data;
}

